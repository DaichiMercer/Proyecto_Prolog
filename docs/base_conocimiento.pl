plataforma_compatible(IdJuego, PlataformaSolicitada) :-
    plataforma(IdJuego, PlataformaSolicitada).

dentro_presupuesto(IdJuego, Presupuesto) :-
    precio(IdJuego, Precio),
    Precio =< Presupuesto.

modo_compatible(IdJuego, cualquiera) :-
    juego(IdJuego, _).
modo_compatible(IdJuego, individual) :-
    modo_juego(IdJuego, individual).
modo_compatible(IdJuego, cooperativo_local) :-
    modo_juego(IdJuego, cooperativo_local).
modo_compatible(IdJuego, cooperativo_en_linea) :-
    modo_juego(IdJuego, cooperativo_en_linea).
modo_compatible(IdJuego, competitivo_en_linea) :-
    modo_juego(IdJuego, competitivo_en_linea).

tiempo_compatible(IdJuego, corta) :-
    duracion_sesion(IdJuego, corta).
tiempo_compatible(IdJuego, media) :-
    duracion_sesion(IdJuego, corta).
tiempo_compatible(IdJuego, media) :-
    duracion_sesion(IdJuego, media).
tiempo_compatible(IdJuego, larga) :-
    duracion_sesion(IdJuego, _).

conexion_compatible(IdJuego, sin_internet) :-
    conexion(IdJuego, offline).
conexion_compatible(IdJuego, sin_internet) :-
    conexion(IdJuego, online_opcional).
conexion_compatible(IdJuego, con_internet) :-
    conexion(IdJuego, _).
conexion_compatible(IdJuego, cualquiera) :-
    juego(IdJuego, _).

genero_coincide(IdJuego, []) :-
    juego(IdJuego, _).
genero_coincide(IdJuego, [Genero|_]) :-
    genero(IdJuego, Genero), !.
genero_coincide(IdJuego, [_|OtrosGeneros]) :-
    genero_coincide(IdJuego, OtrosGeneros).

dificultad_coincide(IdJuego, cualquiera) :-
    juego(IdJuego, _).
dificultad_coincide(IdJuego, DificultadSolicitada) :-
    dificultad(IdJuego, DificultadSolicitada).

juego_viable(PlataformaSolicitada, Presupuesto, ModoSolicitado,
             TiempoDisponible, ConexionUsuario, IdJuego) :-
    plataforma_compatible(IdJuego, PlataformaSolicitada),
    dentro_presupuesto(IdJuego, Presupuesto),
    modo_compatible(IdJuego, ModoSolicitado),
    tiempo_compatible(IdJuego, TiempoDisponible),
    conexion_compatible(IdJuego, ConexionUsuario).

nivel_coincidencia(_, GenerosPreferidos, DificultadPreferida, alta) :-
    GenerosPreferidos \= [],
    DificultadPreferida \= cualquiera, !.
nivel_coincidencia(_, GenerosPreferidos, DificultadPreferida, media) :-
    (GenerosPreferidos \= [] ; DificultadPreferida \= cualquiera), !.
nivel_coincidencia(_, [], cualquiera, general).

recomendar(PlataformaSolicitada, Presupuesto, GenerosPreferidos,
           ModoSolicitado, TiempoDisponible, ConexionUsuario,
           DificultadPreferida, IdJuego, Nombre, Nivel) :-
    juego_viable(PlataformaSolicitada, Presupuesto, ModoSolicitado,
                 TiempoDisponible, ConexionUsuario, IdJuego),
    genero_coincide(IdJuego, GenerosPreferidos),
    dificultad_coincide(IdJuego, DificultadPreferida),
    juego(IdJuego, Nombre),
    nivel_coincidencia(IdJuego, GenerosPreferidos, DificultadPreferida, Nivel).

alternativa(PlataformaSolicitada, Presupuesto, GenerosPreferidos,
            ModoSolicitado, TiempoDisponible, ConexionUsuario,
            DificultadPreferida, IdJuego, Nombre,
            preferencias_no_coinciden) :-
    juego_viable(PlataformaSolicitada, Presupuesto, ModoSolicitado,
                 TiempoDisponible, ConexionUsuario, IdJuego),
    \+ (genero_coincide(IdJuego, GenerosPreferidos),
        dificultad_coincide(IdJuego, DificultadPreferida)),
    juego(IdJuego, Nombre).

motivo_descarte(PlataformaSolicitada, _, _, _, _, IdJuego,
                plataforma_incompatible(PlataformaSolicitada)) :-
    juego(IdJuego, _),
    \+ plataforma(IdJuego, PlataformaSolicitada).

motivo_descarte(_, Presupuesto, _, _, _, IdJuego,
                supera_presupuesto(Precio, Presupuesto)) :-
    juego(IdJuego, _),
    precio(IdJuego, Precio),
    Precio > Presupuesto.

motivo_descarte(_, _, ModoSolicitado, _, _, IdJuego,
                modo_no_disponible(ModoSolicitado)) :-
    juego(IdJuego, _),
    \+ modo_compatible(IdJuego, ModoSolicitado).

motivo_descarte(_, _, _, TiempoDisponible, _, IdJuego,
                tiempo_no_compatible(TiempoDisponible)) :-
    juego(IdJuego, _),
    \+ tiempo_compatible(IdJuego, TiempoDisponible).

motivo_descarte(_, _, _, _, ConexionUsuario, IdJuego,
                conexion_no_compatible(ConexionUsuario)) :-
    juego(IdJuego, _),
    \+ conexion_compatible(IdJuego, ConexionUsuario).


